// Every well-formed string of `n` pairs — the standard open/close-count
// recursion, independent of any submitted solution.
function wellFormed(n: number): string[]
{
  const out: string[] = [];
  const build = (current: string, open: number, close: number) =>
  {
    if (current.length === 2 * n)
    {
      out.push(current);
      return;
    }
    if (open < n) build(current + "(", open + 1, close);
    if (close < open) build(current + ")", open, close + 1);
  };
  build("", 0, 0);
  return out;
}
